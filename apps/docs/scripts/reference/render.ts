/** Small frontmatter/markdown helpers shared by the reference page builders. */

export function yamlString(value: string): string {
  return `"${value.replace(/\\/g, '\\\\').replace(/"/g, '\\"')}"`;
}

export function yamlArray(values: string[]): string {
  return `[${values.map(yamlString).join(', ')}]`;
}

export interface FrontmatterInput {
  title: string;
  description: string;
  audience: string[];
  platforms: string[];
  covers: string[];
}

export function todayIso(): string {
  return new Date().toISOString().slice(0, 10);
}

export function frontmatter({ title, description, audience, platforms, covers }: FrontmatterInput): string {
  const lines = [
    `title: ${yamlString(title)}`,
    `description: ${yamlString(description)}`,
    'type: reference',
    `audience: ${yamlArray(audience)}`,
    `platforms: ${yamlArray(platforms)}`,
    `covers: ${yamlArray(covers)}`,
    'status: published',
    `lastVerified: ${yamlString(todayIso())}`,
  ];
  return `---\n${lines.join('\n')}\n---\n`;
}

export const GENERATED_BANNER = '{/* GENERATED by scripts/gen-reference.ts — do not edit */}';

export function table(headers: string[], rows: string[][]): string {
  const headerRow = `| ${headers.join(' | ')} |`;
  const dividerRow = `|${headers.map(() => '---').join('|')}|`;
  const bodyRows = rows.map((row) => `| ${row.join(' | ')} |`);
  return [headerRow, dividerRow, ...bodyRows].join('\n');
}

export function humanizeEnumName(name: string): string {
  const withoutStatus = name.endsWith('Status') ? name.slice(0, -'Status'.length) : name;
  const withBoundaries = withoutStatus
    .replace(/([A-Z]+)([A-Z][a-z])/g, '$1 $2') // acronym followed by a word, e.g. SMSCampaign
    .replace(/([a-z0-9])([A-Z])/g, '$1 $2') // lowercase/digit followed by a capital
    .trim();
  const words = withBoundaries.split(/\s+/).map((word) => {
    const isAcronym = word.length > 1 && word === word.toUpperCase();
    return isAcronym ? word : `${word.charAt(0).toUpperCase()}${word.slice(1).toLowerCase()}`;
  });
  return `${words.join(' ')} status`;
}
